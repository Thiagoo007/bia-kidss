-- Bia KIDSS: tabela de peças, bucket de fotos e permissões.
-- Cole tudo isto no "SQL Editor" do Supabase e clique em Run. Rode uma vez só.

create table if not exists public.produtos (
  id            bigint generated by default as identity primary key,
  nome          text not null,
  genero        text not null,               -- Meninas, Meninos, Bebês... (a Bia escolhe)
  tamanhos      int[],                       -- vazio/nulo = tamanho a confirmar com a Bia
  tamanho_nota  text,
  preco         numeric(10, 2),              -- nulo = valor pelo WhatsApp
  preco_antigo  numeric(10, 2),              -- preço de antes: preencha para mostrar desconto
  categoria     text,                        -- Vestidos, Conjuntos, ... (a Bia escolhe)
  destaque      boolean not null default false,
  ativo         boolean not null default true,
  foto          text not null,
  foto_w        int,
  foto_h        int,
  miniatura     text,
  mini_w        int,
  mini_h        int,
  ordem         int not null default 0,
  criado_em     timestamptz not null default now()
);

alter table public.produtos enable row level security;

-- Qualquer visitante vê só as peças ativas.
drop policy if exists "visitante ve pecas ativas" on public.produtos;
create policy "visitante ve pecas ativas" on public.produtos
  for select to anon, authenticated using (ativo = true);

-- Só quem entrou com e-mail e senha (a Bia) vê tudo e altera.
drop policy if exists "dona ve tudo" on public.produtos;
create policy "dona ve tudo" on public.produtos
  for select to authenticated using (true);
drop policy if exists "dona cadastra" on public.produtos;
create policy "dona cadastra" on public.produtos
  for insert to authenticated with check (true);
drop policy if exists "dona altera" on public.produtos;
create policy "dona altera" on public.produtos
  for update to authenticated using (true) with check (true);
drop policy if exists "dona exclui" on public.produtos;
create policy "dona exclui" on public.produtos
  for delete to authenticated using (true);

-- Fotos: bucket público para leitura; só a Bia envia, troca e apaga.
insert into storage.buckets (id, name, public) values ('fotos', 'fotos', true)
on conflict (id) do nothing;

drop policy if exists "dona envia fotos" on storage.objects;
create policy "dona envia fotos" on storage.objects
  for insert to authenticated with check (bucket_id = 'fotos');
drop policy if exists "dona troca fotos" on storage.objects;
create policy "dona troca fotos" on storage.objects
  for update to authenticated using (bucket_id = 'fotos');
drop policy if exists "dona apaga fotos" on storage.objects;
create policy "dona apaga fotos" on storage.objects
  for delete to authenticated using (bucket_id = 'fotos');

-- Configurações da loja (WhatsApp, avisos, textos): uma linha só.
create table if not exists public.configuracoes (
  id            int primary key default 1 check (id = 1),
  dados         jsonb not null default '{}'::jsonb,
  atualizado_em timestamptz not null default now()
);
alter table public.configuracoes enable row level security;
drop policy if exists "visitante le configuracoes" on public.configuracoes;
create policy "visitante le configuracoes" on public.configuracoes
  for select to anon, authenticated using (true);
drop policy if exists "dona cadastra configuracoes" on public.configuracoes;
create policy "dona cadastra configuracoes" on public.configuracoes
  for insert to authenticated with check (true);
drop policy if exists "dona altera configuracoes" on public.configuracoes;
create policy "dona altera configuracoes" on public.configuracoes
  for update to authenticated using (true) with check (true);
insert into public.configuracoes (id, dados) values (1, '{}'::jsonb) on conflict (id) do nothing;
